export function speech(line: Speech): string {
  const k = line.kind === undefined ? (current === 'tr' ? 'şey' : 'thing') : propName(line.kind)
  const loc = line.room === undefined ? '' : ROOMS[current][line.room]?.[1] ?? ''
  return SPEECH[current][line.key].replace('{k}', k).replace('{K}', cap(k)).replace('{loc}', loc)
}

