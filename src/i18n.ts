const DICT: Record<Lang, Record<Key, string>> = { tr: TR, en: EN }

let current: Lang = typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en'

export const lang = (): Lang => current
export function setLang(l: Lang): void {
  current = l
  document.documentElement.lang = l
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICT[current][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

